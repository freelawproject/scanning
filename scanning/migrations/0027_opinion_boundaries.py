def blank_measured_runs(apps, schema_editor):
    """Make the collect tick compute every scan in review again.

    :param apps: The historical app registry.
    :param schema_editor: Unused.
    :return: None.
    """
    ExternalJob = apps.get_model("scanning", "ExternalJob")
    heads = ExternalJob.objects.filter(
        stage=DETECT,
        engine=BLACKLETTER,
        provider=RUNPOD,
        shard_index=0,
        apply_run__isnull=True,
        provider_meta__apply__apply_run__isnull=False,
        scan__status__in=RECOMPUTE_STATUSES,
    )
    for head in heads:
        meta = dict(head.provider_meta or {})
        state = dict(meta.get("apply") or {})
        state.pop("apply_run", None)
        meta["apply"] = state
        head.provider_meta = meta
        head.save(update_fields=["provider_meta"])


