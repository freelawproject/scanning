"""The opinion boundaries as rows (issue #240, PR C).

``Scan.opinions_json`` held the output of the pairing as a list of
dicts with no identity and no address. ``OpinionBoundary`` replaces it,
one row per opinion and one per curator decision, and ``OpinionScan``
gets a FK to the boundary its file was cut from (#165).

**No data copy**, as decided in the plan review of 2026-09-09: the
lists were computed from the legacy YOLO trio, and the compute writes
the rows again from the current detections. What fills the table is
the collect tick: for every scan in a review the redaction compute may
be queued from (``PAGE_COMPLETENESS_REVIEW_DONE`` and
``READY_FOR_REDACTION_REVIEW``), the ``apply_run`` of the detect run's
ledger (``provider_meta["apply"]``) is blanked, so
``yolo.redactions_current`` reads "not measured against the standing
run" and ``yolo.queue_ready_runs`` queues the compute on its next tick.
The scan stays in its review throughout, and the compute writes the
boundaries, and the detections and rects again, in the measured space.
A ``REDACTION_REVIEW_DONE`` scan is left alone (#263: a closed review
is not recomputed under the person who closed it), and so is a legacy
scan, which no compute reaches.

Historical models only; the literals are the values of
``models.Status`` and the detect run's identity.
"""

